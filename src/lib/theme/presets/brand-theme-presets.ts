/**
 * brand-theme-presets.ts  — v2 (color overhaul)
 *
 * Premium, opinionated theme presets engineered to make the admin brand stand out.
 *
 * Design philosophy
 * ─────────────────
 * Every preset deliberately controls the ENTIRE visual surface:
 *   • background   → perceptibly tinted, never plain white/grey
 *   • card         → meaningfully lifted off the background (≥ 0.03 L step light, ≥ 0.05 dark)
 *   • ring         → full-chroma primary, not a muted mid-tone
 *   • charts       → 5 perceptually distinct hues, spread across the wheel, high C
 *   • brand/hover gradient → ≥ 40° hue swing for visual punch
 *   • brand-glow   → 0.38–0.48 opacity for dramatic depth
 *   • sidebar      → deep chromatic panel; accent is clearly visible (≥ 0.07 L lift)
 *
 * Token format: oklch(L  C  H)  — L 0–1, C 0–0.4, H 0–360
 */

